import assert from "node:assert/strict";
import { createDraftQueue } from "../src/lib/draftQueue";
import { createContentReuse } from "../src/lib/contentReuse";
import { BUCKET_COLORS, automaticBucketColor, bucketColorClass, formatUTCReset } from "../src/lib/planner";
const memory = new Map<string, string>();
const storage = { getItem: (k: string) => memory.get(k) ?? null, setItem: (k: string, v: string) => { memory.set(k, v); }, removeItem: (k: string) => { memory.delete(k); } };
assert.equal(BUCKET_COLORS.length, 12);
assert.deepEqual(BUCKET_COLORS.slice(0, 4), ["pink", "cyan", "mint", "yellow"]);
for (const color of BUCKET_COLORS) assert.equal(bucketColorClass(color), `bucket-${color}`);
assert.equal(automaticBucketColor(["pink", "cyan"]), "mint");
assert.equal(automaticBucketColor([...BUCKET_COLORS]), "pink");
process.env.TZ = "America/Edmonton";
assert.equal(formatUTCReset("2026-11-01T00:00:00Z"), new Date("2026-11-01T12:00:00Z").toLocaleDateString());
let saved = "original", writes = 0;
const handle = createDraftQueue(async (_, text) => { saved = text; }, storage).open("fictional", "post", saved);
handle.edit("latest unsaved words");
const calls: unknown[] = [];
const reuse = createContentReuse(async request => { writes++; calls.push(request); assert.equal(request.text, saved); return request; }, () => "stable-copy-id");
const first = reuse.run(handle, "post", "instagram", true);
const second = reuse.run(handle, "post", "instagram", true);
assert.equal(first, second);
assert.equal((await first).text, "latest unsaved words");
assert.equal(writes, 1);
await assert.rejects(reuse.run(handle, "post", "unapproved", true), /supported/);
assert.equal(writes, 1);
const failed = createDraftQueue(async () => { throw new Error("offline"); }, storage).open("fictional", "failed", "original");
failed.edit("cannot lose these words");
await assert.rejects(reuse.run(failed, "failed", "twitter", true), /latest wording/);
assert.equal(writes, 1);
assert.equal(failed.get().text, "cannot lose these words");
assert.equal(failed.get().state, "error");
let attempt = 0;
const ids: (string | null)[] = [];
const retry = createContentReuse(async request => { ids.push(request.copyId); if (++attempt === 1) throw new Error("ambiguous network failure"); return request; }, () => crypto.randomUUID());
await assert.rejects(retry.run(handle, "post", "tiktok", true));
await retry.run(handle, "post", "tiktok", true);
assert.equal(ids[0], ids[1]);
console.log("PASS twelve legacy-stable colors, unused-first defaults, UTC reset, latest-text flush, rapid-click coalescing, failed-save stop, retry-stable copy id; no provider calls");