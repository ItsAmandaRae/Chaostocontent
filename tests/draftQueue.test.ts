import assert from "node:assert/strict";
import { createDraftQueue } from "../src/lib/draftQueue";
const memory = new Map<string, string>();
const storage = { getItem: (k: string) => memory.get(k) ?? null, setItem: (k: string, v: string) => { memory.set(k, v); }, removeItem: (k: string) => { memory.delete(k); } };
let unblock: (() => void) | undefined;
const writes: string[] = [];
const queue = createDraftQueue(async (_, text) => { writes.push(text); if (writes.length === 1) await new Promise<void>(r => { unblock = r; }); }, storage);
const first = queue.open("user", "post", "original");
first.edit("early"); const flight = first.flush();
const remount = queue.open("user", "post", "original"); remount.edit("latest");
const concurrent = remount.flush();
assert.equal(writes.length, 1, "Navigation/remount cannot start a concurrent stale write");
unblock?.(); await Promise.all([flight, concurrent]);
assert.deepEqual(writes, ["early", "latest"], "Coalesced text persists after oldest request settles");
remount.edit("reviewed suggestion"); await remount.flush();
assert.equal(writes.at(-1), "reviewed suggestion", "Applying rewrite uses same safe queue");
let fail = true;
const recovery = createDraftQueue(async () => { if (fail) throw new Error("offline"); }, storage);
const failed = recovery.open("user", "failed", "original"); failed.edit("unsaved newest"); await failed.flush();
assert.equal(failed.get().state, "error");
const reload = createDraftQueue(async () => {}, storage).open("user", "failed", "original");
assert.equal(reload.get().text, "unsaved newest", "Hard reload recovers failed edits");
assert.equal(recovery.open("different-user", "failed", "other").get().text, "other", "Recovery scoped by user and post");
fail = false; await failed.flush(); assert.equal(failed.get().state, "saved");
console.log("PASS serialized navigation, coalescing, suggestion apply, failure/recovery and user-scoped backup");